/**
 * One-off image optimisation script.
 *
 * Scans apps/web/src for every images.hostinger.com PNG illustration,
 * downloads each, converts it to WebP at 1600px and 800px wide, saves the
 * results under apps/web/public/images/, and writes a TypeScript manifest at
 * apps/web/src/lib/image-manifest.ts mapping the original URL to the converted
 * files and their pixel dimensions.
 *
 * Run with: node apps/web/scripts/convert-images.cjs
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'src');
const OUT_DIR = path.join(ROOT, 'public', 'images');
const MANIFEST_PATH = path.join(ROOT, 'src', 'lib', 'image-manifest.ts');

const URL_RE = /https:\/\/images\.hostinger\.com\/[A-Za-z0-9\-\/]+\.png/g;

function walk(dir, files = []) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) walk(full, files);
		else if (/\.(ts|tsx)$/.test(entry.name)) files.push(full);
	}
	return files;
}

const urls = new Set();
for (const file of walk(SRC_DIR)) {
	const content = fs.readFileSync(file, 'utf8');
	for (const match of content.matchAll(URL_RE)) urls.add(match[0]);
}

console.log(`Found ${urls.size} unique illustrations`);

fs.mkdirSync(OUT_DIR, { recursive: true });
const manifest = {};
let i = 0;

(async () => {
	for (const url of urls) {
		const slug = url.split('/').pop().replace('.png', '');
		try {
			const res = await fetch(url);
			if (!res.ok) {
				console.error(`  ✗ ${slug} (HTTP ${res.status})`);
				continue;
			}
			const buffer = Buffer.from(await res.arrayBuffer());
			const meta = await sharp(buffer).metadata();
			const origW = meta.width || 1600;
			const origH = meta.height || 900;
			const w1600 = Math.min(1600, origW);
			const w800 = Math.min(800, origW);
			const h1600 = Math.round(origH * (w1600 / origW));

			await sharp(buffer).resize({ width: w1600 }).webp({ quality: 80 }).toFile(path.join(OUT_DIR, `${slug}.webp`));
			await sharp(buffer).resize({ width: w800 }).webp({ quality: 75 }).toFile(path.join(OUT_DIR, `${slug}-800.webp`));

			manifest[url] = {
				webp: `/images/${slug}.webp`,
				webp800: `/images/${slug}-800.webp`,
				width: w1600,
				height: h1600,
			};
			i += 1;
			console.log(`  ✓ ${i}/${urls.size} ${slug} ${origW}x${origH} -> ${w1600}w`);
		} catch (err) {
			console.error(`  ✗ ${slug}: ${err.message}`);
		}
	}

	const body = JSON.stringify(manifest, null, 2);
	const ts = `// AUTO-GENERATED by scripts/convert-images.cjs — do not edit by hand.\nexport const imageManifest: Record<string, { webp: string; webp800: string; width: number; height: number }> = ${body};\n`;
	fs.writeFileSync(MANIFEST_PATH, ts);
	console.log(`\nWrote manifest with ${Object.keys(manifest).length} entries`);
})();
